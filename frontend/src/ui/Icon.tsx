export type IconName = keyof typeof ICONS;

export function Icon({ name, className = 'h-5 w-5', label }: { name: IconName; className?: string; label?: string }) {
  const Glyph = ICONS[name];
  return <Glyph strokeWidth={1.75} className={`shrink-0 ${className}`} role={label ? 'img' : undefined} aria-label={label} aria-hidden={label ? undefined : true} />;
}
